/// Verify that a theme-variant directory exists in ~/.local/share/vogix/themes/
///
/// All theme configs are pre-generated by home-manager at build time.
/// This function verifies the expected directory exists before persisting state.
/// Called after engine.next() but before state.save() — prevents invalid state on disk.
pub fn verify_theme_variant_exists(theme: &str, variant: &str) -> Result<PathBuf> {
    let themes_dir = crate::config::Config::themes_dir();
    let theme_path = themes_dir.join(format!("{}-{}", theme, variant));

    if !theme_path.exists() {
        return Err(VogixError::ThemeNotFound(format!(
            "theme variant {}-{} not found at {}",
            theme,
            variant,
            theme_path.display()
        )));
    }

    Ok(theme_path)
}

/// The polarity ("dark" or "light") of a theme variant, read from the
/// config.toml manifest — the SAME value the Nix render layer wrote there —
/// so the two layers cannot disagree on it. The "dark" fallback mirrors the
/// Nix side's `variantData.polarity or "dark"`.
pub fn variant_polarity(scheme: &Scheme, theme: &str, variant: &str) -> String {
    discover_themes()
        .ok()
        .and_then(|themes| {
            themes
                .into_iter()
                .find(|t| t.name == theme && t.scheme == *scheme)
        })
        .and_then(|t| {
            t.variants
                .into_iter()
                .find(|v| v.name == variant)
                .map(|v| v.polarity)
        })
        .unwrap_or_else(|| "dark".to_string())
}
